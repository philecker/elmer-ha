/**
 * Turn Elmer's brand mark into the single filled path the sidebar needs.
 *
 * Home Assistant's custom-iconset API hands back one `d` string, drawn with
 * fill and no stroke. The mark is the opposite: five stroked shapes at a
 * 1.95 weight, with round caps and joins. Redrawing it filled by eye would
 * drift from the glyph used everywhere else in the panel, and the two would
 * then drift further apart with every tweak — so the outline is computed from
 * the same source string the panel renders.
 *
 * The geometry is done in Python, where shapely has a proper buffer: each
 * stroked subpath becomes a polyline, the polyline is buffered by half the
 * stroke weight with round caps and joins, and the union of those is the
 * filled shape. This file only extracts the mark from icons.js and writes the
 * result back, so the two cannot be edited apart.
 *
 * Run it after changing the mark: node tools/build-sidebar-icon.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const ICONS = path.join(ROOT, 'custom_components/elmer/frontend/icons.js');
const OUT = path.join(ROOT, 'custom_components/elmer/frontend/sidebar-icon.js');

const src = fs.readFileSync(ICONS, 'utf8');
const m = src.match(/\n\s*mark:\s*'([^']*)'/);
if (!m) throw new Error('could not find the mark in icons.js');
const mark = m[1];

const weight = Number((mark.match(/stroke-width="([\d.]+)"/) || [])[1]);
if (!weight) throw new Error('the mark has no stroke-width');

// The shapes the mark is built from, in the order they are drawn.
const shapes = [];
for (const d of mark.matchAll(/<path d="([^"]+)"/g)) shapes.push({ kind: 'path', d: d[1] });
for (const r of mark.matchAll(/<rect ([^>]+)\/>/g)) {
  const at = (k) => Number((r[1].match(new RegExp(`${k}="([\\d.-]+)"`)) || [])[1]);
  shapes.push({
    kind: 'rect', x: at('x'), y: at('y'), w: at('width'), h: at('height'), rx: at('rx'),
  });
}
if (!shapes.length) throw new Error('the mark has no shapes');

const out = execFileSync('python3', [path.join(HERE, 'outline-stroke.py')], {
  input: JSON.stringify({ weight, shapes }),
  encoding: 'utf8',
});
const { d, area } = JSON.parse(out);

const body = `/* Generated by tools/build-sidebar-icon.mjs — do not edit by hand.

   Elmer's brand mark as one filled path, for Home Assistant's sidebar.

   The sidebar takes an icon name, not an image, and a custom icon set hands
   back a single path drawn with fill rather than stroke. This is the outline
   of the stroked mark in icons.js, computed from that same string, so the
   sidebar and the panel header cannot drift apart.

   Registered on every page through frontend.add_extra_js_url, because the
   sidebar is drawn long before anybody opens the panel. */
window.customIconsets = window.customIconsets || {};
window.customIconsets.elmer = async () => ({
  path: '${d}',
});

/* Home Assistant looks an icon set up once and never again.

   ha-icon resolves in willUpdate, and only when its own icon property
   changes. If the set is missing at that moment it sets a legacy flag and
   renders <iron-icon>, an element the frontend no longer ships, so nothing is
   drawn. There is no event, no retry and nothing that notices the set
   arriving later — the row stays empty for the life of the page, which is why
   a reload appears to fix it.

   This file is fetched over the network on every page load, so whether it
   wins the race against the sidebar's first paint varies with the
   connection. Losing it should not cost the icon until the next reload.

   So: having registered, go and find any icon of ours that already gave up,
   and change its icon property to something else and back. That is the one
   thing ha-icon watches, and resolution now succeeds because the registry is
   read live. The walk is bounded and only descends into shadow roots.

   An icon that resolved perfectly well is left alone, which is nearly all of
   them: ha-icon hands the path it found down to the ha-svg-icon it renders,
   so one with a path is working and one without is not. That is read as a
   property rather than by looking for the <iron-icon> the legacy branch
   renders, because the property survives a frontend that stops rendering
   that element while the symptom stays the same. */
(() => {
  const PREFIX = 'elmer:';

  /* Has this one actually got a drawing in it? */
  function drawn(el) {
    try {
      const svg = el.shadowRoot && el.shadowRoot.querySelector('ha-svg-icon');
      return !!(svg && svg.path);
    } catch {
      return false;
    }
  }

  function repair() {
    const roots = [document];
    const seen = new Set();
    const stale = [];
    let budget = 4000;

    while (roots.length && budget > 0) {
      const root = roots.pop();
      if (!root || seen.has(root)) continue;
      seen.add(root);
      let nodes;
      try {
        nodes = root.querySelectorAll('*');
      } catch {
        continue;
      }
      for (const el of nodes) {
        if (--budget <= 0) break;
        // An element that has not upgraded yet has no icon property, and it
        // will resolve correctly on its own once it does. Only one that has
        // already run and come back empty needs anything doing to it.
        if (el.localName === 'ha-icon'
          && typeof el.icon === 'string'
          && el.icon.startsWith(PREFIX)
          && !drawn(el)) {
          stale.push(el);
        }
        if (el.shadowRoot) roots.push(el.shadowRoot);
      }
    }

    for (const el of stale) {
      const icon = el.icon;
      try {
        el.icon = '';
        el.icon = icon;
      } catch {
        /* Not ours to fix if the property will not take. */
      }
    }
    return stale.length;
  }

  // Now, for a sidebar that drew before this file arrived. Again at load for
  // one that is drawing right now: a second pass over a handful of elements
  // is cheaper than being wrong until the next reload.
  try {
    repair();
    if (document.readyState !== 'complete') {
      window.addEventListener('load', () => {
        try {
          repair();
        } catch {
          /* ignored */
        }
      }, { once: true });
    }
  } catch {
    /* An icon is not worth throwing on somebody else's page. */
  }
})();
`;

const rel = path.relative(ROOT, OUT);

// --check is for the verifier: the file is generated, so the mark can be
// edited without it, and the sidebar would then quietly keep the old drawing
// — which is the one thing this whole arrangement exists to prevent.
if (process.argv.includes('--check')) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (have !== body) {
    console.error(`${rel} is out of step with the mark in icons.js.`);
    console.error('Run: node tools/build-sidebar-icon.mjs');
    process.exit(1);
  }
  console.log(`${rel} matches the mark`);
} else {
  fs.writeFileSync(OUT, body);
  console.log(`${rel}  ${d.length} chars, area ${area.toFixed(2)}`);
}
